def render(d: dict) -> str:
    day_pl = d["equity"] - d["last_equity"]
    day_pct = day_pl / d["last_equity"] * 100 if d["last_equity"] else 0
    total_pl = sum(p["pl"] for p in d["positions"])
    closed = d["n_sells"]
    win_rate = d["n_targets"] / closed * 100 if closed else None
    regime = d["regime"] or {}

    tiles = f"""
<div class="tiles">
  <div class="tile"><div class="label">Equity {'(paper)' if d['paper'] else '(LIVE)'}</div>
    <div class="value">{_fmt_money(d['equity'])}</div>
    <div class="delta {_cls(day_pl)}">{day_pl:+,.2f} ({day_pct:+.2f}%) today</div></div>
  <div class="tile"><div class="label">Cash</div>
    <div class="value">{_fmt_money(d['cash'])}</div></div>
  <div class="tile"><div class="label">Open P/L</div>
    <div class="value {_cls(total_pl)}">{total_pl:+,.2f}</div>
    <div class="delta">{len(d['positions'])} position{'s' if len(d['positions']) != 1 else ''}</div></div>
  <div class="tile"><div class="label">Closed trades</div>
    <div class="value">{closed}</div>
    <div class="delta">{d['n_targets']} targets · {d['n_stops']} stops"""
    tiles += (f" · {win_rate:.0f}% wins" if win_rate is not None else "") + "</div></div>"
    tiles += f"""
  <div class="tile"><div class="label">Macro regime</div>
    <div class="value" style="font-size:20px">{regime.get('regime', '—')}</div>
    <div class="delta">score {regime.get('score', 0):+.2f} · exposure x{regime.get('exposure_multiplier', '—')}</div></div>
</div>"""

    halt_banner = ("<p class='badge' style='color:var(--bad);border-color:var(--bad)'>"
                   "⛔ CIRCUIT BREAKER ACTIVE — no new entries today</p>" if d["halted"] else "")

    pos_rows = "".join(
        f"<tr><td>{p['symbol']}</td><td>{p['qty']:.4f}</td><td>{_fmt_money(p['entry'])}</td>"
        f"<td>{_fmt_money(p['price'])}</td><td>{_fmt_money(p['value'])}</td>"
        f"<td class='{_cls(p['pl'])}'>{p['pl']:+,.2f} ({p['pl_pct']:+.1f}%)</td>"
        f"<td>{p['stop'] if p['stop'] else '—'}</td><td>{p['target'] if p['target'] else '—'}</td></tr>"
        for p in d["positions"]) or "<tr><td colspan=8>No open positions</td></tr>"

    sig_rows = ""
    for t, s in sorted((d["signals"].get("signals") or {}).items(),
                       key=lambda kv: kv[1]["score"], reverse=True)[:12]:
        top = sorted(s["components"], key=lambda c: abs(c["score"] * c["weight"]), reverse=True)
        drivers = "; ".join(f"{c['name']} {c['detail']}" for c in top[:2] if c["detail"])
        flags = " ".join(f"⚠️{html.escape(f)}" for f in s.get("risk_flags", []))
        sig_rows += (f"<tr><td>{t}</td><td class='{_cls(s['score'])}'>{s['score']:+.3f}</td>"
                     f"<td>{s['conviction']}</td>"
                     f"<td style='text-align:left'>{html.escape(drivers)} {flags}</td></tr>")
    sig_rows = sig_rows or "<tr><td colspan=4>No signal snapshot yet — run a scan</td></tr>"

    mem_rows = "".join(
        f"<tr><td>{html.escape(m)}</td><td>{v['n_trades']}</td>"
        f"<td class='{_cls(v['mean_excess_30td'])}'>{v['mean_excess_30td']:+.1%}</td>"
        f"<td>{v['hit_rate']:.0%}</td><td>{v['weight']:.2f}</td></tr>"
        for m, v in sorted(d["members"].items(), key=lambda kv: kv[1]["weight"],
                           reverse=True)[:10]
    ) or "<tr><td colspan=5>Run: python3 member_scoring.py build</td></tr>"

    trade_rows = "".join(
        f"<tr><td>{t.get('timestamp', '')[:16]}</td><td>{t.get('action', '').upper()}</td>"
        f"<td>{t.get('ticker', '')}</td>"
        f"<td>{_fmt_money(t['notional']) if t.get('notional') else '—'}</td>"
        f"<td style='text-align:left'>{html.escape((t.get('why') or t.get('thesis') or '')[:90])}</td></tr>"
        for t in reversed(d["trades"])) or "<tr><td colspan=5>No trades logged yet</td></tr>"

    return f"""<!doctype html><html><head><meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1">
<title>Sovereign Dashboard</title><style>{CSS}</style></head><body>
<h1>🏦 Sovereign — {'Paper' if d['paper'] else 'LIVE'} Trading Dashboard</h1>
<p class="sub">Generated {d['generated']} · goal: fund the Hand ($400) · discipline over ambition</p>
{halt_banner}
{tiles}
<h2>Equity — last 3 months</h2>
<div class="card">{_equity_svg(d['equity_curve'])}</div>
<h2>Open positions</h2>
<div class="card"><table>
<tr><th>Symbol</th><th>Qty</th><th>Entry</th><th>Price</th><th>Value</th><th>P/L</th><th>Stop</th><th>Target</th></tr>
{pos_rows}</table></div>
<h2>Latest composite signals</h2>
<div class="card"><table>
<tr><th>Ticker</th><th>Score</th><th>Conviction</th><th style="text-align:left">Top drivers</th></tr>
{sig_rows}</table></div>
<h2>Congressional leaderboard (30-trading-day excess vs SPY)</h2>
<div class="card"><table>
<tr><th>Member</th><th>N</th><th>Excess</th><th>Hit%</th><th>Weight</th></tr>
{mem_rows}</table></div>
<h2>Recent trades</h2>
<div class="card"><table>
<tr><th>When</th><th>Action</th><th>Ticker</th><th>Notional</th><th style="text-align:left">Why</th></tr>
{trade_rows}</table></div>
</body></html>"""


def main():
    d = gather()
    OUT_FILE.write_text(render(d))
    log.info("Dashboard written to %s", OUT_FILE)

    day_pl = d["equity"] - d["last_equity"]
    print(f"\nSOVEREIGN — equity {_fmt_money(d['equity'])} ({day_pl:+,.2f} today) | "
          f"cash {_fmt_money(d['cash'])} | {len(d['positions'])} positions | "
          f"regime {(d['regime'] or {}).get('regime', '?')}"
          f"{' | ⛔ HALTED' if d['halted'] else ''}")
    for p in d["positions"]:
        print(f"  {p['symbol']:6s} {_fmt_money(p['value']):>10s}  "
              f"{p['pl']:+7.2f} ({p['pl_pct']:+.1f}%)  stop={p['stop']} target={p['target']}")
    print(f"Dashboard: {OUT_FILE}")


if __name__ == "__main__":
    main()
