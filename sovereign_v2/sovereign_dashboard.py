"""Sovereign dashboard — performance tracking as a self-contained HTML page.

Pulls live account + portfolio history from Alpaca, closed-trade stats from
sovereign_state/trade_log.jsonl, the latest composite signals, macro regime,
and the congressional member leaderboard. Writes:

    sovereign_results/dashboard.html   (open in any browser; light/dark aware)

and prints a CLI summary. Regenerated by cron at market close.

Usage:  python3 sovereign_dashboard.py
"""

import html
import json
import logging
from datetime import datetime

from sovereign_config import (DATA_DIR, RESULTS_DIR, STATE_DIR, alpaca_keys,
                              load_json)

logging.basicConfig(level=logging.INFO, format="%(asctime)s %(message)s")
log = logging.getLogger("dashboard")

OUT_FILE = RESULTS_DIR / "dashboard.html"


# --------------------------------------------------------------------------
# Data gathering
# --------------------------------------------------------------------------

def gather() -> dict:
    from alpaca.trading.client import TradingClient
    from alpaca.trading.requests import GetPortfolioHistoryRequest

    key, secret, paper = alpaca_keys()
    client = TradingClient(key, secret, paper=paper)
    account = client.get_account()
    positions = client.get_all_positions()

    equity_curve = []
    try:
        hist = client.get_portfolio_history(GetPortfolioHistoryRequest(
            period="3M", timeframe="1D"))
        for ts, eq in zip(hist.timestamp, hist.equity):
            if eq is not None:
                equity_curve.append({"date": datetime.fromtimestamp(ts).strftime("%m/%d"),
                                     "equity": float(eq)})
    except Exception as e:
        log.warning("Portfolio history failed: %s", e)

    trades = []
    trade_log = STATE_DIR / "trade_log.jsonl"
    if trade_log.exists():
        for line in trade_log.read_text().splitlines():
            try:
                trades.append(json.loads(line))
            except json.JSONDecodeError:
                continue

    sells = [t for t in trades if t.get("action") == "sell"]
    stops = sum(1 for t in sells if "STOP" in t.get("why", ""))
    targets = sum(1 for t in sells if "TARGET" in t.get("why", ""))

    snaps = sorted(RESULTS_DIR.glob("signals_*.json"), reverse=True)
    signals = load_json(snaps[0], {}) if snaps else {}
    regime = load_json(RESULTS_DIR / "macro_regime.json", {})
    members = load_json(DATA_DIR / "member_scores.json", {}).get("members", {})
    state = load_json(STATE_DIR / "positions_state.json", {})
    halt = load_json(STATE_DIR / "halt.json", {})

    return {
        "paper": paper,
        "equity": float(account.equity),
        "last_equity": float(account.last_equity or account.equity),
        "cash": float(account.cash),
        "positions": [{
            "symbol": p.symbol, "qty": float(p.qty),
            "entry": float(p.avg_entry_price), "price": float(p.current_price),
            "value": float(p.market_value), "pl": float(p.unrealized_pl),
            "pl_pct": float(p.unrealized_plpc) * 100,
            "stop": state.get(p.symbol, {}).get("stop"),
            "target": state.get(p.symbol, {}).get("target"),
        } for p in positions],
        "equity_curve": equity_curve,
        "trades": trades[-20:],
        "n_buys": sum(1 for t in trades if t.get("action") == "buy"),
        "n_sells": len(sells), "n_stops": stops, "n_targets": targets,
        "signals": signals, "regime": regime, "members": members,
        "halted": halt.get("date") == datetime.now().strftime("%Y-%m-%d"),
        "generated": datetime.now().strftime("%Y-%m-%d %H:%M"),
    }


